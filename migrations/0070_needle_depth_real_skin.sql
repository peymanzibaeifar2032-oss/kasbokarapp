۹. فرق عمق در ناحیه‌های بدن

ضخامت پوست خیلی متغیر است. ناحیهٔ نازک (پلک، مچ داخلی، آرنج داخلی، انگشت، گردن) عمق کمتر و فشار کمتر می‌خواهد. ناحیهٔ ضخیم (بالای پشت، ران، ساعد) تحمل بیشتری دارد.
عمقی که برای پشت مناسب است ممکن است روی پلک یا مچ داخلی بلوآوت بسازد. تنظیم با کشش پوست و حس مقاومت است، نه با یک میلی‌متر برای همه جا.

۱۰. چرا رنگ تازه خوب است و بعد از ترمیم ضعیف می‌شود؟

- مقدار زیادی جوهر در اپیدرم بوده و جدا شده.
- تورم و پلاسما اول کار را غلیظ‌تر نشان داده.
- اشباع درم کم بوده: عمق کم یا پاس ناکافی.
- زیاده‌کاری باعث شده پوست جوهر را پس بزند.
- بعضی رنگدانه‌ها، به‌خصوص روشن‌تر، در التهاب و با ماکروفاژ بیشتر از دست می‌روند.
اگر عمق عمدتاً اپیدرمی باشد، محو شدن شدیدتر است.

