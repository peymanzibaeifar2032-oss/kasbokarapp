- زیاده‌کاری از اشباع ناکامل آسیب‌زننده‌تر است. اشباع ناکامل را می‌شود بعداً ترمیم کرد.

۱۳. باورهای اشتباه

- «برای رنگ باید عمیق‌تر بروی.» اثبات نشده. لایهٔ هدف همان است.
