- بالا بردن ولتاژ همیشه اشباع را بهتر می‌کند.
- نشستن کامل کارتریج روی پوست (riding the tube) روش ایده‌آل است. کنترل را کمتر می‌کند.

۱۴. جمع‌بندی برای کار حرفه‌ای

عمق نفوذ سوزن را از عمق نهایی رنگ جدا کن. هدف، نشستن یکنواخت و کافی رنگ در درم پاپیلاری و بالای رتیکولار است، با کمترین آسیب. در کار رنگی و پر کردن سنگین، تراکم از تکنیک می‌آید: حرکت تنگ، پاس کنترل‌شده، جریان خوب جوهر. نه از عمیق‌تر رفتن. به پاسخ پوست نگاه کن. ناحیهٔ نازک را محافظه‌کارانه‌تر کار کن. سلامت بافت را جلوتر از اشباع همان جلسه بگذار.

