این درس عمق سوزن را روی پوست واقعی جدا می‌کند: سوزن تا کجا می‌رود، رنگ در کدام لایه می‌ماند، و در کار رنگی عمق را چطور از روی خود پوست می‌خوانند. عدد ثابت برای همهٔ پوست‌ها وجود ندارد. عمق مؤثر به ضخامت پوست، ناحیهٔ بدن، سن، تکنیک و پاسخ همان لحظهٔ پوست بستگی دارد.

شواهد بافت‌شناسی از تجربهٔ کارگاهی جدا نوشته شده است. هر جا عدد یا توصیه از آموزش هنرمند یا فروشندهٔ ابزار آمده، همان‌جا گفته شده و قانون علمی برای همهٔ پوست‌ها نیست.

۱. عمق ورود سوزن و جای رنگ

پوست سه لایهٔ اصلی دارد.

اپیدرم (Epidermis)، روپوست: لایهٔ نازک، معمولاً ۰٫۰۵ تا ۰٫۱۵ میلی‌متر؛ در کف دست و پا ضخیم‌تر. رگ خونی ندارد و مدام عوض می‌شود (چرخه حدود ۲۸ تا ۴۰ روز). رنگی که فقط اینجا بنشیند با سلول‌های مرده می‌ریزد و در ۴ تا ۶ هفته محو می‌شود.

درم (Dermis)، میان‌پوست: لایهٔ هدف. دو بخش دارد.
- درم پاپیلاری (Papillary dermis): لایهٔ بالایی و نازک، حدود ۰٫۱ تا ۰٫۳ میلی‌متر، بافت همبند شل، رگ زیاد و ماکروفاژ. محل اصلی ماندگاری پایدار.
- درم رتیکولار (Reticular dermis): ضخیم‌تر و متراکم‌تر، با کلاژن نوع یک. رنگ را نگه می‌دارد، اما رفتن عمیق‌تر خطر پخش رنگ (blowout، بلوآوت) را زیاد می‌کند.

هیپودرم (Hypodermis)، لایهٔ چربی: رسیدن سوزن به اینجا پخش دائمی جوهر و آسیب بیشتر می‌سازد.

شواهد علمی
مطالعهٔ اولشفسکا و همکاران (Olszewska et al., Histology and Histopathology, 2023، جلد ۳۸، صفحهٔ ۵۰۳ تا ۵۱۱، DOI: 10.14670/HH-18-559، PMID: 36468542) روی پوست تتوشدهٔ سینه، شکم، دلتوئید و ساعد نشان داد رنگ عمدتاً در لایهٔ پاپیلاری درم است و به‌ندرت نزدیک رتیکولار. عمق با ضخامت درم و اپیدرم همبستگی مثبت داشت و با سن تتو همبستگی منفیِ ضعیف. در آن نمونه‌ها ساعد عمیق‌ترین و دلتوئید و سینه کم‌عمق‌ترین بود.
مطالعات میکروسکوپ الکترونی (Lea و Pawlowski، International Journal of Dermatology، ۱۹۸۷، DOI: 10.1111/j.1365-4362.1987.tb00590.x) و تصویربرداری TPE-FLIM روی کربن‌بلک و رنگ‌های رنگی (۲۰۲۳ تا ۲۰۲۶) می‌گویند رنگدانه‌ها بیشتر درون سلول، در ماکروفاژ، فیبروبلاست و ماست‌سل درم می‌مانند. مقداری هم حتی در تتوهای قدیمی در اپیدرم دیده می‌شود.
ضخامت درم در بدن تا حدود ۸ برابر فرق می‌کند: پلک حدود ۰٫۵ تا ۰٫۷ میلی‌متر، کمر بالایی تا حدود ۳٫۵ تا ۴ میلی‌متر. هدف عملی‌ای که در ادبیات زیاد تکرار می‌شود حدود ۱ تا ۲ میلی‌متر زیر سطح برای بیشتر ناحیه‌هاست؛ یعنی ورود به پاپیلاری تا بخش بالایی رتیکولار. این عدد قانون همهٔ پوست‌ها نیست.

تفکیک مهم: عمق نفوذ سوزن (مسافتی که نوک در هر ضربه می‌رود) با عمق نهایی رنگ یکی نیست. سوزن کانال می‌سازد. جوهر با کشش مویرگی و فشار وارد می‌شود و بعد سلول‌های ایمنی و فیبروبلاست آن را در شبکهٔ کلاژن نگه می‌دارند. بخشی از جوهر اضافه از راه لنف خارج می‌شود.

نکتهٔ کلیدی: رنگ باید به درم پاپیلاری تا بخش بالایی رتیکولار برسد تا بماند. فقط اپیدرم یعنی ریزش. هیپودرم یعنی بلوآوت. این اصل هم در بافت‌شناسی هست و هم در آموزش‌های هنرمندان (از جمله Tattooing 101 و راهنمای فروشندگان ابزار). آموزش هنرمند جایگزین مطالعهٔ بافت نیست.

۲. عمق در تاتوی رنگی، پرترهٔ رنگی و رنگ سنگین

برای بیشتر کارهای رنگی و پر کردن رنگ (color packing) هدف همان درم است، معمولاً حدود ۱ تا ۲ میلی‌متر بسته به ناحیه. فرق اصلی در تراکم و تعداد پاس و در کنترل دقیق‌تر عمق است، نه عوض کردن لایهٔ هدف.
در پرتره و رئالیسم رنگی، به‌خاطر لایه‌گذاری نرم و پرهیز از آسیب زیاد (که جوهر را پس می‌زند یا بافت را ناهموار می‌کند)، عمق معمولاً محافظه‌کارانه‌تر و با پاس‌های کنترل‌شده است. در اشباع سنگین گاهی از کورس بلندتر و عمق کمی بیشتر در ناحیهٔ ضخیم استفاده می‌شود تا با پاس کمتر رنگ بنشیند؛ باز هم نباید از مرز درم بگذرد.
شاهد علمی قوی نیست که خودِ سبک رنگی لایهٔ دیگری بخواهد. فرق‌ها بیشتر فنی است.

۳. آیا هر رنگ عمق جدا می‌خواهد؟

شاهد علمی برای عمق متفاوت بر اساس نوع رنگ کم است. اندازهٔ ذرات (غالباً حدود ۲۰ تا ۴۰۰ نانومتر، با تجمع‌های بزرگ‌تر) و ترکیب شیمیایی روی ماندگاری، مقاومت در برابر ماکروفاژ و محو شدن اثر دارد. رنگ‌های روشن‌تر و زرد و سفید اغلب ذرهٔ کوچک‌تر دارند و زودتر کم‌رنگ می‌شوند. لایهٔ هدف همان درم است.
رنگ‌های کم‌پوشش (سفید، زرد روشن، بعضی پاستل‌ها) تراکم بالاتر می‌خواهند تا بعد از ترمیم پر دیده شوند، نه لزوماً عمق بیشتر. نفوذ زیاد در همهٔ رنگ‌ها خطر بلوآوت و آسیب بافت دارد.

۴. قطر سوزن، تعداد، کارتریج، تیپر و چیدمان

- قطر بزرگ‌تر (۰٫۳۵ تا ۰٫۴۰ میلی‌متر در برابر باگ‌پین ۰٫۲۵) و چیدمان مگنوم (M1 و RM) در هر پاس جوهر بیشتری می‌برد و برای پر کردن مناسب‌تر است، اما سطح را بیشتر آزار می‌دهد.
- تیپر بلند: ورود نرم‌تر و کنترل دقیق‌تر عمق. مناسب جزئیات و رئالیسم.
- تیپر کوتاه: سوراخ بازتر و حمل جوهر بیشتر. مناسب پر کردن سنگین.
- چیدمان گرد (RL و RS) برای خط و جزئیات. مگنوم برای پوشش و اشباع.
این‌ها کارایی رسوب رنگ و میزان آسیب را عوض می‌کنند، نه لایهٔ هدف را. سوزن نازک‌تر راحت‌تر فرو می‌رود و فشار کمتری می‌خواهد.

۵. ولتاژ، کورس، سرعت دست، زاویه و فشار

- کورس (Stroke): برای پر کردن رنگ اغلب ۳٫۵ تا ۵ میلی‌متر گفته می‌شود؛ بلندتر برای سطح بزرگ. کورس کوتاه‌تر در پاس‌های بعدی آسیب کمتری می‌سازد. این محدوده‌ها توصیهٔ آموزشی و فروشنده است، نه عدد پزشکی ثابت.
- ولتاژ: برای روتاری معمولاً حدود ۷ تا ۹ ولت، بسته به دستگاه، سوزن و سرعت دست. ولتاژ بالا پرش و آسیب می‌سازد. ولتاژ پایین رنگ را کم می‌نشاند. ولتاژ ابزار است، راه‌حل اصلی نیست. اگر اشباع ضعیف است اول عمق، سرعت دست، جریان جوهر و کشش پوست را ببین.
- سرعت دست: برای اشباع، آهسته و کنترل‌شده نسبت به سرعت دستگاه. حرکت تند تکه‌تکه کار می‌کند.
- زاویه: حدود ۴۵ درجه برای مگنوم تا پوست بریده نشود و رنگ یکنواخت‌تر پخش شود.
- فشار: حداقل. فقط نوک سوزن کار کند (float). فشار زیاد عمق را از حد می‌برد.

نکتهٔ کلیدی: تعادل سرعت دستگاه و سرعت دست، خواندن مقاومت سبک پوست (نه کشیدن سنگین)، و کشش درست. در آموزش‌های Tattooing 101 و راهنماهای World Famous و Ultimate Tattoo Supply هم آمده که بالا بردن ولتاژ اولین جواب اشباع ضعیف نیست. این توصیهٔ صنفی است.

۶. پر کردن رنگ و پرترهٔ رنگی بدون آسیب زیاد

- مگنوم، اغلب ۷ تا ۱۳، از نوع M1 یا RM.
- سوزن را شناور نگه دار؛ فقط نوک‌ها در پوست.
- حرکت کوچک، تنگ و دایره‌ای یا بیضی، با هم‌پوشانی حدود ۳۰ تا ۵۰ درصد.
- چند پاس کنترل‌شده. بین پاس‌ها پوست را نگاه کن.
- از تیره به روشن کار کن.
- نشانهٔ زیاده‌کاری را جدی بگیر: قرمزی شدید، تورم، پس زدن جوهر. اشباع کمی کمتر و ترمیم بعدی بهتر از پوست آسیب‌دیده است.
در رئالیسم رنگی لایه‌گذاری نرم‌تر و محو با حرکت شلاقی و پاندولی مهم‌تر است. پر کردن سنگین فقط در ناحیه‌ای است که باید واقعاً اشباع شود.

