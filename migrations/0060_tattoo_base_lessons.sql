جمع‌بندی
تاتوی تمیز یعنی رنگ در جای درست پوست، با وسیله‌ای که یا یک‌بارمصرف و باز نشده است، یا درست تمیز و استریل شده. بیشتر خطاهای خطرناک از صرفه‌جویی در سوزن، برگرداندن رنگ به بطری، و دستکش آلوده می‌آید. فصل بعد چیدمان همین وسایل روی میز است تا بخش تمیز و بخش کثیف قاطی نشود.

پیشنهاد تصویرها
۱. میز از بالا، با نیمهٔ تمیز و نیمهٔ کثیف و فلش مسیر دست. دلیل: کارآموز قبل از مشتری، چیدمان را تمرین کند.
۲. سه برچسب کنار هم: تمیز کردن، ضدعفونی، استریل، با یک مثال برای هر کدام. دلیل: این سه کلمه بیشترین اشتباه لفظی را می‌سازند.
