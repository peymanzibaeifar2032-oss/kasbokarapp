۲. سه کلمه را قاطی نکن
تمیز کردن: کندن خون، رنگ و چربی با آب و شوینده. اگر کثیفی بماند، ضدعفونی و استریل هر دو ضعیف می‌شوند.

ضدعفونی (disinfection): کشتن بخش زیادی از میکروب‌های روی سطح. میز، دسته و روکش را ضدعفونی می‌کنند. ضدعفونی، سوزن را استریل نمی‌کند.

استریلیزاسیون (sterilization): از بین بردن همهٔ شکل‌های میکروب، از جمله هاگ، روی وسیله‌ای که باید استریل باشد. برای فلز مقاوم به حرارت، روش مرجع بخار تحت فشار یعنی اتوکلاو است.

الکل روی سوزن استفاده شده، استریل نیست. جوشاندن در آب معمولی هم جایگزین اتوکلاو نیست.

۳. چه چیزی یک‌بارمصرف است
سوزن و کارتریجی که پوست را سوراخ کرده، بعد از یک مشتری دور ریخته می‌شود. شستن و اتوکلاو کردن سوزن مصرف‌شده برای مشتری بعدی قابل قبول نیست. کارتریج برای یک نفر طراحی شده و تیزبودن و بسته‌بودنش بعد از استفاده تضمین نیست.

