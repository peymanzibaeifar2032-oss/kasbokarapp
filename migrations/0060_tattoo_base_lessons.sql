مبتدی

مقدمه
تاتو رنگ را روی سطح پوست نمی‌کشد. رنگ باید در لایهٔ میانی پوست بنشیند و همان‌جا بماند. اگر این لایه را نشناسی، خط یا کم‌رنگ می‌شود و می‌ریزد، یا از زیر پوست پخش می‌شود و لکه‌ای تار می‌سازد. این فصل فقط آناتومی لازم برای تاتو است: لایه‌ها، سلول‌هایی که رنگ را نگه می‌دارند، تفاوت ضخامت پوست در جاهای مختلف بدن، و دو خطای اصلی عمق.

بدنه

۱. پوست سه بخش دارد
پوست از بیرون به داخل سه بخش دارد.

اپیدرم (epidermis) لایهٔ بیرونی و نازک است. سلول‌هایش مدام می‌میرند و می‌ریزند. رنگی که فقط در اپیدرم باشد، با پوست‌اندازی از بین می‌رود.

درم (dermis) لایهٔ میانی است. محکم‌تر است، رگ و عصب و کلاژن دارد، و سلول‌هایش مثل اپیدرم هر چند هفته عوض نمی‌شوند. جای درست رنگ تاتو همین‌جاست، بیشتر در بخش بالایی درم.

هیپودرم (hypodermis) یا چربی زیرپوست، لایهٔ عمیق است. جای رنگ نیست. رنگ اگر به این عمق برسد پخش می‌شود. به این پخش‌شدگی در کار تاتو بلوآوت (blowout) می‌گویند.

تصویر لازم
برش عرضی پوست با سه لایه، یک سوزن که نوکش در بالای درم ایستاده، و یک سوزن اشتباه که وارد چربی شده. کارآموز باید فرق «نشستن رنگ» و «پخش رنگ» را در یک نگاه ببیند.

۲. اپیدرم لایه‌لایه است
از بیرون به داخل:

لایهٔ شاخی (stratum corneum): سلول مرده و فشرده. سد اصلی در برابر میکروب و آب است. سوزن باید از این لایه رد شود، ولی خراش سطحیِ همین لایه رنگ ماندگار نمی‌سازد.

لایهٔ شفاف (stratum lucidum): فقط در پوست ضخیم دیده می‌شود، مثل کف دست و کف پا. در بازو و ساق نیست.

لایهٔ دانه‌دار (stratum granulosum): سلول‌ها اینجا دانه‌های کراتین دارند و سد پوست کامل‌تر می‌شود.

لایهٔ خاردار (stratum spinosum): ضخیم‌ترین بخش اپیدرم در بیشتر جاهای بدن.

لایهٔ پایه (stratum basale): یک ردیف سلول زنده که سلول تازه می‌سازد. ملانوسیت (melanocyte)، سلول رنگ‌دانهٔ خود پوست، همین‌جاست. رنگ پوست مشتری از همین سلول می‌آید، نه از درم.

اپیدرم تقریباً هر چهار هفته یک‌بار نو می‌شود. این عدد در همه‌جا و همه‌کس یکسان نیست، ولی مبدأ آموزش همین است: رنگ سطحی مهمان موقتی است. در هفته‌های اولِ خوب‌شدن، پوست نو اپیدرم را می‌سازد و رنگ اضافهٔ سطحی با پوسته‌ریزی می‌رود. رنگی که در درم نشسته باشد می‌ماند.

تصویر لازم
پنج لایهٔ اپیدرم با نام فارسی و نام انگلیسی، و یک علامت جدا که نشان بدهد لایهٔ شفاف فقط در کف دست و کف پاست.

۳. درم دو بخش دارد
درمِ پاپیلاری (papillary dermis) بخش بالایی و نازک‌تر است. شل‌تر است، مویرگ زیاد دارد و با اپیدرم دندانه‌دندانه قفل می‌شود. بخش زیادی از رنگِ درستِ تاتو در همین محدوده و کمی پایین‌تر قرار می‌گیرد.

درمِ رتیکولار (reticular dermis) عمیق‌تر و سفت‌تر است. دستهٔ کلاژن ضخیم دارد. رنگ اگر بیش از حد پایین برود، هم دیرتر و نامنظم‌تر می‌نشیند و هم راحت‌تر به اطراف پخش می‌شود.

زیر این‌ها چربی است. چربی برای نگه‌داشتن خط ساخته نشده. خط در چربی لبهٔ تمیز ندارد.

بررسی میکروسکوپی پوست تاتوشده نشان داده رنگ در درم می‌ماند، نه در اپیدرمِ نو. این مشاهده پایهٔ همان چیزی است که در کار عملی می‌بینی: بعد از خوب شدن، فقط رنگی می‌ماند که به عمق درست رسیده باشد. (Lea و Pawlowski، ۱۹۸۷)

تصویر لازم
بزرگ‌نمایی مرز اپیدرم و درم. دانه‌های رنگ داخل درم بالایی. یک فلش جدا برای رنگی که اشتباهی وارد چربی شده و لکه ساخته.

۴. چه کسی رنگ را نگه می‌دارد
رنگ تاتو ذره است، نه مایعِ جادویی که «جذب پوست» شود. بعد از ورود سوزن، بخشی از ذره‌ها را سلول‌های بیگانه‌خوار یعنی ماکروفاژ (macrophage) می‌بلعند. بخشی کنار رشته‌های کلاژن و در سلول‌های فیبروبلاست (fibroblast) می‌ماند. این سلول‌ها در درم عمر بلند دارند، برای همین طرح سال‌ها دیده می‌شود.

همهٔ ذره‌ها سر جای اول نمی‌مانند. بخشی با روند خوب‌شدن و دستگاه لنفاوی از پوست خارج می‌شود. پژوهش با روش‌های تصویربرداری پیشرفته، رنگ تاتو را در غدهٔ لنفاوی نزدیک محل تاتو هم نشان داده است. (Schreiver و همکاران، ۲۰۱۷) این پیدا شدن به‌تنهایی تشخیص سرطان نیست، ولی باید بدانی رنگ فقط «همان نقطه» نمی‌ماند. به مشتری هم نباید بگویی رنگ کاملاً بی‌حرکت و بی‌اثر است.

تصویر لازم
طرح ساده از یک ماکروفاژ که دانهٔ رنگ را بلعیده، کنار رشتهٔ کلاژن. بدون شکل ترسناک و بدون ادعای پزشکی اضافه.

۵. ضخامت پوست همه‌جا یکی نیست
یک تنظیم دستگاه، برای همهٔ بدن یک عمق نمی‌سازد.

پلک و پوست دور چشم بسیار نازک است. کار روی پلک کار مبتدی نیست.

داخل بازو، دنده، و برخی جاهای روی استخوان، پوست نازک‌تر یا شل‌تر است و رنگ راحت‌تر پخش می‌شود.

کف دست، کف پا و گاهی روی زانو پوست ضخیم‌تر است. لایهٔ شاخی آنجا زیاد است. این جاها هم از نظر بهداشت و هم از نظر ماندن رنگ، کار پیشرفته‌اند و جای تمرین اول نیستند.

روی مفصل، پوست مدام جمع و باز می‌شود. خط صافِ روی کاغذ، روی مفصل تغییر شکل می‌دهد.

روی جای جوش فعال، زخم باز، آفتاب‌سوختگی، اگزما یا پوسته‌ریزی، سوزن نزن. سد پوست خراب است و هم عفونت راحت‌تر است، هم رنگ نامنظم می‌نشیند.

تصویر لازم
نقشهٔ سادهٔ بدن با چهار نشانه: نازک، معمولی، ضخیم، و «اینجا برای کارآموز ممنوع». بدون عکس واقعیِ زخم.

۶. عمق درست یعنی چه
عدد میلی‌متر یک قانون ثابت برای همهٔ بدن نیست. اپیدرم در پلک کسر کوچکی از میلی‌متر است و در کف پا خیلی ضخیم‌تر. درم هم چند میلی‌متر ضخامت دارد و در افراد مختلف فرق می‌کند. (آموزش پوست در منابع پوست‌شناسی، از جمله Bolognia)

پس عمق را از حفظ کردن یک عدد یاد نگیر. عمق را از نتیجه بشناس:

اگر سوزن فقط اپیدرم را خراشیده، رنگ همان جلسه غلیظ و خیس دیده می‌شود ولی در خوب‌شدن می‌ریزد و طرح کم‌رنگ یا ناقص می‌ماند.

اگر رنگ در درم بالایی نشسته باشد، خط بعد از خوب شدن هنوز هست، لبهٔ اضافه ندارد و زیر پوست هالهٔ خاکستری نساخته.

اگر سوزن به درم عمیق یا چربی رفته باشد، همان روز یا در خوب‌شدن دور خط یک سایهٔ پخش دیده می‌شود. این بلوآوت است. با فشار بیشتر و دور دومِ سنگین درست نمی‌شود؛ اغلب بدتر می‌شود.

علامت‌های حین کار که کارآموز باید بشناسد، نه اینکه با آن‌ها خوددرمانی کند:
رنگ که درست نشسته، پوست کمی قرمز و یکنواخت است و رنگ در خط می‌ماند.
خون زیاد و مداوم یعنی به رگ و عمق نامناسب نزدیک شده‌ای. کار را تمیز نگه دار و فشار را کم کن. اگر خون بند نمی‌آید، کار آموزشی را ادامه نده.
سفید شدن شدید و پاره شدن لایهٔ سطحی یعنی آسیب اضافه. این «نشستن بهتر رنگ» نیست.

۷. رگ، عصب و ضمائم
در درم رگ‌های کوچک، عصب، غدهٔ عرق، غدهٔ چربی و پیاز مو هست. سوزن از کنار این‌ها رد می‌شود. برای همین تاتو درد دارد و گاهی خون می‌آید. درد به‌تنهایی نشانهٔ عمق درست نیست. بعضی جاها مثل روی استخوان و کشاله با عمق معمولی هم درد زیاد دارند.

مو را نباید کند تا «کار راحت شود» اگر مشتری راضی نیست و اگر پوست را زخم می‌کنی. تراشیدن درست، با وسیلهٔ یک‌بارمصرف و بدون خراش، در فصل بهداشت می‌آید.

۸. رنگ خود پوست و رنگ تاتو
ملانین در لایهٔ پایهٔ اپیدرم است. روی پوست تیره، رنگ روشن تاتو ضعیف‌تر دیده می‌شود چون از پشتِ پوستِ تیره‌تر نگاه می‌شود. این ضعفِ دست تو نیست؛ فیزیک نور و پوست است. سفید و زرد روی پوست خیلی تیره اغلب آن‌قدر که روی کاغذ دیده می‌شوند، دیده نمی‌شوند. این را قبل از کار بگو، نه بعد از خوب شدن.

