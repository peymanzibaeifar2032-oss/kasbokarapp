پوستی که مشتری می‌گوید با رنگ مو، فلز یا چسب زخم تاول و حساسیت شدید می‌دهد. فصل عوارض جداست؛ اینجا فقط بدان که باید قبل از سوزن بپرسی و در شک، کار را عقب بیندازی.
