۱. اصل پایه
خون و مایع بدن هر مشتری را آلوده فرض کن، حتی اگر خودش بگوید سالم است. خیلی از ناقل‌های هپاتیت علامت ندارند. این همان احتیاط استاندارد (standard precautions) است که مراکز کنترل بیماری آمریکا برای تماس با خون آموزش می‌دهد. (CDC، Bloodborne Pathogens)

یعنی:
دستکش را برای ظاهر نمی‌پوشی. دستکش مانع تماس پوست تو با خون اوست.
سوزن استفاده شده را از نو استریل حساب نمی‌کنی.
بطری رنگ را با دست آلوده لمس نمی‌کنی.
