رنگ را از بطری اصلی مستقیم روی پوست نریز. مقدار لازم را در کاپ یک‌بارمصرف بریز. باقی‌ماندهٔ کاپ را به بطری برنگردان. سر بطری نباید به دستکش آلوده یا به کاپ بخورد.

۴. دست و دستکش
قبل از پوشیدن دستکش، دست را با آب و صابون بشوی. اگر دست نمایان کثیف نیست و فقط بین مراحل است، محلول الکلی دست می‌تواند طبق دستور همان محصول استفاده شود، ولی دست خون‌آلود را اول باید شست. (CDC، بهداشت دست)

دستکش:
برای هر مشتری یک جفت نو.
اگر پاره شد، عوضش کن.
اگر با دستکش آلوده صورت، تلفن، بطری رنگ یا دستگیره را گرفتی، آن دستکش دیگر تمیز نیست. دستکش نو بپوش.
دستکش تو را در برابر فرورفتن سوزن محافظت کامل نمی‌کند. سوزن آلوده اگر به دستت رفت، دستکش کافی نبوده.

ناخن بلند، انگشتر و دستبند زیر دستکش، دستکش را سوراخ می‌کند. در زمان کار دربیاور.

۵. آماده‌کردن پوست
محدوده را با تیغ یک‌بارمصرف، بدون زخم کردن، اصلاح کن. پوست را با مادهٔ ضدعفونی مناسب پوست بشوی و بگذار خشک شود. ماده را از روی بطری اصلی به گاز تمیز منتقل کن. دهانهٔ بطری را به پوست یا گاز آلوده نزن.

بعد از چسباندن استنسیل، اگر پوست را دوباره زیاد می‌شویی، طرح می‌رود. این دلیل نمی‌شود که پوست کثیف بماند. اصلاح و ضدعفونی باید قبل از استنسیل درست انجام شده باشد. اگر وسط کار پوست به چیزی آلوده شد، کار را نگه دار، دستکش را عوض کن و همان ناحیه را دوباره تمیز کن.

۶. پوشش و منطقهٔ تمیز
هر چیزی که دست آلوده ممکن است لمس کند، یا یک‌بارمصرف است یا با پوشش تعویض‌شونده محافظت می‌شود: بند دستگاه، بطری آب یا وازلین، چراغ، دستهٔ تخت.

میز را به دو بخش فکری تقسیم کن.
بخش تمیز: سوزن باز نشده، کاپ نو، رنگ هنوز باز نشده، دستکش نو.
بخش کثیف: سوزن باز شده، گاز خون‌آلود، کاپ استفاده شده.

سوزن را روی بخش تمیز برنگردان.

۷. اتوکلاو فقط برای وسیلهٔ درست
اگر گریپ یا تیوب فلزی چندبارمصرف داری، باید بعد از هر مشتری تمیز، بسته‌بندی و اتوکلاو شود. چرخه را از روی دفترچهٔ همان دستگاه و دستور معتبر انتخاب کن، نه از حافظهٔ یک عدد ثابت. بسته باید نشانگر داشته باشد که نشان بدهد حرارت به بسته رسیده.

اتوکلاو را با آزمون اسپور (spore test) دوره‌ای کنترل می‌کنند. نشانگر چسبی فقط می‌گوید بسته حرارت دیده. آزمون اسپور می‌گوید دستگاه واقعاً میکروب مقاوم را کشته یا نه. اگر آزمون مردود بود، وسیله‌های آن دوره را استریل‌شده حساب نکن.

سوزن کارتریج، چوب، پلاستیک ناسازگار با بخار، و هر چیز یک‌بارمصرف را داخل اتوکلاو «برای صرفه‌جویی» برنگردان.

۸. پسماند تیز
سوزن، تیغ و هر چیز تیز آلوده مستقیم به سطل زبالهٔ معمولی نمی‌رود. در ظرف مقاوم به سوراخ (sharps container) انداخته می‌شود. درِ ظرف را با دست به سمت سوزن فشار نده. ظرف که به خط پر شدن رسید، عوض می‌شود. فشردنش برای جا شدن بیشتر، دست را سوراخ می‌کند.

گاز خون‌آلود طبق قاعدهٔ پسماند همان شهر دور ریخته می‌شود. اگر نمی‌دانی قاعدهٔ محلی چیست، قبل از کار کردن بپرس. حدس نزن.

۹. اگر سوزن به دست خودت رفت
کار روی مشتری را متوقف کن.
دستکش را دربیاور. محل را با آب و صابون بشوی. محل را نکن و نخار. روی زخم مادهٔ ناشناخته نریز.
خون مشتری را هم اگر لازم است با گاز تمیز کنترل کن و دستکش نو بپوش، یا کار را به کسی بسپار که دستش سالم است.
زمان، نوع سوزن و شرح تماس را یادداشت کن.
هر چه زودتر به مرکز درمانی یا اورژانس مراجعه کن. برای هپاتیت B، اگر واکسن نزده باشی، ممکن است ایمونوگلوبولین و واکسن در ساعت‌های اول مطرح شود. این تصمیم پزشک است، نه تصمیم داخل استودیو. (CDC، قرارگیری شغلی با خون)

واکسن هپاتیت B برای کسی که با خون کار می‌کند توصیهٔ استاندارد است. واکسن جای دستکش و اتوکلاو را نمی‌گیرد.

۱۰. چه چیزهایی در اتاق کار جایی ندارند
خوردن و سیگار در محدودهٔ کار.
تبدیل سوزن بین دو مشتری.
لمس تلفن با دستکش آلوده و بعد ادامهٔ کار با همان دستکش.
گذاشتن رنگ باقی‌مانده در کاپ برای مشتری بعدی، حتی اگر «رنگ گرانی» باشد.
کار کردن با زخم باز روی انگشت خودت، بدون پوشش غیرقابل نفوذ و بدون توقف کار.
تاتو روی پوست عفونی. فصل پوست را ببین.

نکات کلیدی و هشدارها
خون هر کس را آلوده فرض کن.
ضدعفونی با استریل یکی نیست. الکل سوزن کارکرده را نو نمی‌کند.
سوزن و کارتریج یک مشتری، برای مشتری بعد ممنوع است.
رنگ از کاپ به بطری برنمی‌گردد.
دستکش آلوده به بطری، تلفن و صورت نمی‌خورد.
