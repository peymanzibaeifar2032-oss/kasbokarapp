/** Studio facts. Empty string means this question is not covered here. */
export function answerStudioQuestion(question: string): string {
  const q = question.replace(/[؟?]/g, "").replace(/\s+/g, " ").trim();
  if (q.length < 2) return "";
  const before = /قبل/.test(q) && /مراقبت|آماده|جلسه|تاتو/.test(q);
  const after = /بعد/.test(q) && /مراقبت|ترمیم|بهبود|بهبودی|تاتو/.test(q);
  if (before && after) return `${BEFORE} بعد از کار: ${AFTER}`;
  if (before) return BEFORE;
  if (after) return AFTER;
  if (/درد|بی\s*حسی|بیحسی|تحمل|طاقت/.test(q)) return PAIN;
  if (/پوست/.test(q) && /رنگ|تیره|روشن|گندمی/.test(q)) return SKIN;
  if (/پوسته|زخم|ریزش|خارش|دلمه/.test(q)) return AFTER;
  if (/استخر|دریا|سونا|جکوزی|آفتاب|ورزش|حمام|دوش/.test(q)) return WHEN;
  if (/تماس|شماره|زنگ|تلفن|واتس|پیامک/.test(q)) {
    return `برای تماس با آرتیست همین شماره را بگیر: ${STUDIO_CONTACT_PHONE}`;
  }
  if (/آدرس|کجاست|کجا هست|چطور بیام|چجوری بیام/.test(q)) {
    return `استودیو: ${STUDIO_ADDRESS}. تلفن: ${STUDIO_CONTACT_PHONE}`;
  }
  if (/متریال|کیفیت|سوزن|جوهر|لوازم|بهداشت|یکبار|یک‌بار|آمریک/.test(q)) {
    return "همه متریال آمریکایی است و تمام لوازم یکبار مصرف است.";
  }
  if (/خودش|خودت|کی میزن|کی می‌زن|پیمان|هنرجو|کارآموز|استاد/.test(q)) {
    return `بله. تاتو را خود ${STUDIO_OWNER_STAFF_NAME} انجام می‌دهد، نه کارآموز.`;
  }
  if (/پنجشنبه|پنج‌شنبه/.test(q)) {
    return "پنجشنبه‌ها فقط برای کارآموزهاست و نوبت مشتری ثبت نمی‌شود.";
  }
  if (/قیمت|هزینه|چقدر|چند تومن|میلیون/.test(q)) {
    return "قیمت را خود آرتیست بعد از دیدن طرح، محل و اندازه می‌گوید. اینجا عدد قیمت گفته نمی‌شود.";
  }
  if (/چند ساعت|طول میکشد|طول می‌کشد|چقدر طول/.test(q)) {
    return "زمان دقیق بعد از دیدن طرح گفته می‌شود. جلسه می‌تواند چند ساعت باشد و اگر کار طولانی باشد در چند جلسه انجام می‌شود.";
  }
  if (/بیعانه|کارت به کارت|واریز|شبا/.test(q)) {
    return "بعد از تأیید درخواست، شماره کارت و مبلغ بیعانه در وضعیت همین شماره برایت می‌آید. تا رسید تأیید نشود نوبت قطعی نیست.";
  }
  if (/گردن|ساعد|بازو|انگشت|سینه|شکم|پهلو|کمر|پشت|زانو|ساق|ران|مچ/.test(q) && /امکان|میخوام|می‌خوام|میشه|می‌شه|بزن|هست/.test(q)) {
    return `بله، این محل انجام می‌شود و کار را خود ${STUDIO_OWNER_STAFF_NAME} می‌زند. اندازه و عکس طرح را در درخواست بنویس تا زمان دقیق گفته شود.`;
  }
  if (/مراقبت/.test(q)) return `${BEFORE} بعد از کار: ${AFTER}`;
  return "";
}

export function cleanAssistantAnswer(text: string) {
  const value = text.replace(/\s+/g, " ").trim();
  if (!value || !/[\u0600-\u06FF]/.test(value)) {
    return `این را بهتر است از خود آرتیست بپرسی. تلفن: ${STUDIO_CONTACT_PHONE}`;
  }
  if (/[0-9۰-۹]+[\s\d۰-۹٬,.]{0,12}(میلیون|تومان)/.test(value)) {
    return "قیمت را خود آرتیست بعد از دیدن طرح، محل و اندازه می‌گوید. اینجا عدد قیمت گفته نمی‌شود.";
  }
  return value.slice(0, 900);
}
