function normalize(value: string) {
  return value.replace(/[ي]/g, "ی").replace(/[ك]/g, "ک").replace(/[‌\s]+/g, " ").trim().toLowerCase();
}

const STOP = new Set(["است", "این", "آن", "را", "در", "از", "با", "به", "که", "برای", "چه", "یک", "رو", "می", "شود", "نیست", "هست", "تو", "من", "ما", "اگر", "یا", "هم"]);

function tokens(value: string) {
  return normalize(value)
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => (word.length >= 2 || /^\d+$/.test(word)) && !STOP.has(word));
}

export function retrieveLessons(query: string, limit = 4): ApprenticeLesson[] {
  const words = tokens(query);
  const map = APPRENTICE_LESSONS.find((lesson) => lesson.id === "map");
  if (!words.length) return map ? [map] : APPRENTICE_LESSONS.slice(0, 1);
  const ranked = APPRENTICE_LESSONS.map((lesson) => {
    const hay = normalize(`${lesson.title} ${lesson.tags.join(" ")} ${lesson.body}`);
    let score = 0;
    for (const word of words) {
      if (hay.includes(word)) score += word.length >= 4 ? 3 : 2;
    }
    for (const tag of lesson.tags) {
      if (normalize(query).includes(normalize(tag))) score += 4;
    }
    return { lesson, score };
  })
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score);
  const picked = ranked.slice(0, limit).map((row) => row.lesson);
  if (!picked.length) return map ? [map] : [];
  if (map && !picked.some((lesson) => lesson.id === "map") && picked.length < limit) picked.push(map);
  return picked;
}

