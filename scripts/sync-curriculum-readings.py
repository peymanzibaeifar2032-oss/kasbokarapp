#!/usr/bin/env python3
"""Copy editor-approved chapters (edited/STATUS.md DONE lines, never *.notes.md) into the app and book."""
import json, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
ED = pathlib.Path("/workspace/apprentice-curriculum-collab/edited")
status = (ED / "STATUS.md").read_text()
done = re.findall(r"^DONE \| (\d\d-[a-z0-9-]+)\.md", status, re.M)
held = re.findall(r"^HELD \| (\d\d-[a-z0-9-]+)\.md", status, re.M)
wanted = [l.split('"')[1] for l in (ROOT / "src/lib/tattoo-curriculum/readings.ts").read_text().splitlines() if re.match(r'\s+"\d\d-', l) and l.count('"') >= 4 and "cur-" not in l]
# Our own fact-check corrections, applied on top of the editor's text (verified 2026-11-10).
FIXES = {
    "20-reference-copyright": [
        ("ولی بعد آن را برای بررسی هیئت کامل ابطال کرد (۹ ژوئن ۲۰۲۶). جلسهٔ استماع ۲۹ سپتامبر ۲۰۲۶ برگزار شد و تا زمان نگارش این درس (نوامبر ۲۰۲۶) **حکم نهایی صادر نشده است**",
         "ولی در ۹ ژوئن ۲۰۲۶ دستور رسیدگی دوباره با هیئت ۱۱ نفره (En banc) داد و رأی هیئت سه‌نفره را ابطال کرد. جلسهٔ استماع ۲۹ سپتامبر ۲۰۲۶ برگزار شد؛ طبق فهرست رسمی پرونده‌های En banc دادگاه حوزهٔ نهم (به‌روزشده ۱ نوامبر ۲۰۲۶) پرونده «استماع‌شده و در انتظار رأی» است و تا ۱۰ نوامبر ۲۰۲۶ **رأی نهایی صادر نشده است**"),
        ("[صفحهٔ پرونده؛ ASMP](https://www.asmp.org/advocacy/sedlik-v-von-drachenberg/) |",
         "[صفحهٔ پرونده؛ ASMP](https://www.asmp.org/advocacy/sedlik-v-von-drachenberg/)؛ [دادگاه تجدیدنظر حوزهٔ نهم، پرونده‌های En banc](https://www.ca9.uscourts.gov/cases/en-banc/) |"),
        ("6. ASMP — Sedlik v. Von Drachenberg (صفحهٔ پرونده؛ ASMP طرف حامی عکاس است) — https://www.asmp.org/advocacy/sedlik-v-von-drachenberg/",
         "6. ASMP — Sedlik v. Von Drachenberg (صفحهٔ پرونده؛ ASMP طرف حامی عکاس است) — https://www.asmp.org/advocacy/sedlik-v-von-drachenberg/\n6a. U.S. Court of Appeals for the Ninth Circuit — Status of Pending En Banc Cases (1 Nov 2026; No. 24-3367: argued and submitted 29 Sep 2026) — https://www.ca9.uscourts.gov/cases/en-banc/"),
    ],
}
out = {}
for name in wanted:
    if name == "00-glossary":
        out[name] = (ED / "glossary.md").read_text(); print("ok", name, len(out[name])); continue
    if name not in done or name in held:
        print("SKIP (not DONE)", name); continue
    text = (ED / f"{name}.md").read_text()
    # Owner decision 2026-11-10: publish everything; internal review markers are stripped, never shown.
    text = re.sub(r"\s*\**\[?\s*نیاز به تأیید\s*\]?\**", "", text)
    for old, new in FIXES.get(name, []):
        if old not in text: print("FIX NOT APPLIED", name, old[:40]); sys.exit(1)
        text = text.replace(old, new)
    out[name] = text
    print("ok", name, len(text))
ts = ["// Generated by scripts/sync-curriculum-readings.py from the editor's ready-to-publish chapters. Do not edit.",
      "export const READING_TEXT: Record<string, string> = " + json.dumps(out, ensure_ascii=False, indent=1) + ";", ""]
(ROOT / "src/lib/tattoo-curriculum/readings.generated.ts").write_text("\n".join(ts))
book = ROOT / "docs/apprentice-book/readings"; book.mkdir(parents=True, exist_ok=True)
for k, v in out.items(): (book / f"{k}.md").write_text(v)
