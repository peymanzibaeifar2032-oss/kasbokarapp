def fa(text: str) -> str:
    return get_display(arabic_reshaper.reshape(text))


def wrap(text: str, limit: int = 28) -> list[str]:
    words = text.split()
    lines, cur = [], ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if len(trial) > limit and cur:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines[:3]


def panel(steps: list[str], title: str) -> Image.Image:
    im = Image.new("RGB", (1000, 860), CREAM)
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((16, 16, 984, 844), 24, outline=NAVY, width=3)
    d.text((940, 36), fa(title), font=FONT, fill=NAVY, anchor="ra")
    colors = [TEAL, NAVY, (168, 68, 62)]
    for i, step in enumerate(steps):
        y = 120 + i * 230
        d.rounded_rectangle((40, y, 960, y + 200), 18, outline=colors[i], width=4)
        d.ellipse((70, y + 70, 150, y + 150), fill=colors[i])
        d.text((110, y + 92), str(i + 1), font=FONT, fill=CREAM, anchor="mm")
        for n, line in enumerate(wrap(step)):
            d.text((900, y + 48 + n * 42), fa(line), font=FONT_SM, fill=NAVY, anchor="ra")
    return im


def jpeg(im: Image.Image) -> str:
    im = im.convert("RGB")
    im.thumbnail((1000, 860))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=62, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def skin_photo() -> Image.Image:
    src = Image.open(SKIN).convert("RGB")
    w, h = src.size
    src = src.crop((int(w * 0.30), 0, w, h))
    src.thumbnail((760, 760))
    canvas = Image.new("RGB", (1000, 860), CREAM)
    canvas.paste(src, (20, 80))
    d = ImageDraw.Draw(canvas)
    d.text((980, 28), fa("برش واقعی پوست"), font=FONT, fill=NAVY, anchor="ra")
    labels = [(150, "اپیدرم"), (340, "درم سطحی"), (560, "درم عمقی")]
    for y, label in labels:
        d.rounded_rectangle((800, y, 980, y + 54), 8, fill=NAVY)
        d.text((890, y + 27), fa(label), font=FONT_SM, fill=CREAM, anchor="mm")
