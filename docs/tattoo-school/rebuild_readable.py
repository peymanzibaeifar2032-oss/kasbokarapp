import arabic_reshaper
from bidi.algorithm import get_display
from PIL import Image, ImageDraw, ImageFont

spec = importlib.util.spec_from_file_location("bp", "/workspace/docs/tattoo-school/build_practice.py")
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)

FONT_B = ImageFont.truetype("/workspace/docs/tattoo-school/fonts/Vazirmatn-Bold.ttf", 46)
FONT_M = ImageFont.truetype("/workspace/docs/tattoo-school/fonts/Vazirmatn-Bold.ttf", 40)
FONT_N = ImageFont.truetype("/workspace/docs/tattoo-school/fonts/Vazirmatn-Bold.ttf", 42)
CREAM = (244, 239, 230)
NAVY = (28, 61, 82)
WHITE = (255, 252, 247)
TEAL = (47, 111, 104)
NUMS = "۱۲۳"


def fa(text: str) -> str:
    return get_display(arabic_reshaper.reshape(text))


def wrap(text: str, font: ImageFont.FreeTypeFont, max_w: int) -> list[str]:
    words = text.replace("،", " ،").split()
    lines, cur = [], ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if font.getlength(fa(trial)) > max_w and cur:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def board(title: str, steps: list[str]) -> Image.Image:
    width = 1080
    text_w = 760
    wrapped = [wrap(step, FONT_M, text_w) for step in steps]
    row_h = [max(150, 36 + len(lines) * 58) for lines in wrapped]
    height = 150 + sum(row_h) + 40
    im = Image.new("RGB", (width, height), CREAM)
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((24, 24, width - 24, height - 24), 28, fill=WHITE, outline=NAVY, width=4)
    d.text((width - 56, 48), fa(title), font=FONT_B, fill=NAVY, anchor="ra")
    y = 130
    for i, lines in enumerate(wrapped):
        h = row_h[i]
        d.rounded_rectangle((48, y, width - 48, y + h - 16), 22, fill=CREAM, outline=TEAL, width=4)
        cx = width - 110
        cy = y + (h - 16) / 2
        d.ellipse((cx - 36, cy - 36, cx + 36, cy + 36), fill=NAVY)
        d.text((cx, cy), NUMS[i], font=FONT_N, fill=WHITE, anchor="mm")
        ty = cy - (len(lines) * 58) / 2 + 8
        for n, line in enumerate(lines):
            d.text((cx - 64, ty + n * 58), fa(line), font=FONT_M, fill=NAVY, anchor="rm")
        y += h
    return im


