def to_jpeg(im: Image.Image) -> str:
    import base64
    import io

    im = im.convert("RGB")
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=86, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


